import { mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { withQaBrowser } from '../../qa/browser.mjs';

const target = new URL('../assets/', import.meta.url);
await mkdir(target, {recursive: true});
const origin = process.argv[2] ?? 'http://127.0.0.1:5188/';
const address = new URL(origin);
if (!['localhost', '127.0.0.1', '[::1]'].includes(address.hostname)) throw new Error('A local development server is required.');
await withQaBrowser(async ({ page }) => {
  await page.goto(new URL('/trial/scripts/check-model.mjs', address).href);
  const result = await page.evaluate(async () => {
    const exporter = await import('/node_modules/three/examples/jsm/exporters/GLTFExporter.js');
    const { createArt, makeBike } = await import('/src/world-art.js');
    const art = createArt();
    try {
      const { root } = makeBike(art);
      root.name = 'NiuBiExpress_local_rider_and_scooter';
      root.userData.provenance = 'Locally authored procedural riding proxy; not generated by Aholo Lux3D.';
      root.updateMatrixWorld(true);
      const buffer = await new exporter.GLTFExporter().parseAsync(root, { binary: true, onlyVisible: true });
      const bytes = new Uint8Array(buffer);
      const chunk = 8192;
      const parts = [];
      for (let offset = 0; offset < bytes.length; offset += chunk) {
        parts.push(String.fromCharCode(...bytes.subarray(offset, offset + chunk)));
      }
      return btoa(parts.join(''));
    } finally { art.dispose(); }
  });
  const key = new URL('骑手与鬼火-操控代理.glb', target);
  const bytes = Buffer.from(result, 'base64');
  if (bytes.toString('ascii', 0, 4) !== 'glTF' || bytes.readUInt32LE(8) !== bytes.length) throw new Error('Incomplete GLB stream.');
  await writeFile(key, bytes);
  console.log('Local gameplay model:', fileURLToPath(key), bytes.length, 'bytes');
});
